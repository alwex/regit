import { $ } from 'execa'
import fs from 'fs'
import path from 'path'
import { TestContext, describe, expect, test } from 'vitest'

const REPO_ROOT = path.resolve(__dirname, '..')
const TSC = path.join(REPO_ROOT, 'node_modules', '.bin', 'tsc')

const typeCheckHooksFile = async (ctx: TestContext, source: string) => {
    const projectDir = ctx.tempDirLocal
    fs.writeFileSync(path.join(projectDir, 'hooks.js'), source)
    fs.writeFileSync(
        path.join(projectDir, 'tsconfig.json'),
        JSON.stringify({
            compilerOptions: {
                allowJs: true,
                checkJs: true,
                noEmit: true,
                strict: true,
                skipLibCheck: true,
                target: 'es2020',
                module: 'commonjs',
                moduleResolution: 'node',
                baseUrl: '.',
                paths: { 'regit-cli': [REPO_ROOT] },
            },
            files: ['hooks.js'],
        })
    )

    return $(TSC, ['-p', projectDir], { reject: false, cwd: projectDir })
}

const validHooksFile = `
/** @type {(context: import('regit-cli').FeatureRemoveContext) => string} */
const describeRemoval = (context) => {
    return context.id + ' ' + context.branch
}

/** @type {(context: import('regit-cli').ReleaseRemoveContext) => string} */
const describeAbortedRelease = (context) => {
    return context.version + ' ' + context.releaseBranch + ' ' + context.features.length
}

/** @type {(context: import('regit-cli').PreviewRemoveContext) => string[]} */
const previewFeatureBranches = (context) => {
    return context.features.map((feature) => {
        return context.previewBranch + ':' + feature.branch
    })
}

/** @type {import('regit-cli').Hooks} */
const hooks = {
    postFeatureStart: async (id, context) => {
        if (context.origin === 'new' && !context.isOutdated) {
            console.log(id, context.baseTag)
        }
    },
    getTagMessage: async (version, context) => {
        return context.features
            .map((feature) => {
                return feature.branch
            })
            .join(', ')
    },
    postReleaseFinish: async (version, context) => {
        console.log(context.stableCommit, context.deletedBranches.length)
    },
    postFeatureRemove: async (id, context) => {
        console.log(describeRemoval(context))
    },
    postPreviewRemove: async (preview, context) => {
        console.log(previewFeatureBranches(context))
    },
    postReleaseRemove: async (version, context) => {
        console.log(describeAbortedRelease(context))
    },
}

module.exports = hooks
`

const invalidHooksFile = `
/** @type {import('regit-cli').Hooks} */
const hooks = {
    getTagMessage: async (version, context) => {
        return context.features.length
    },
}

module.exports = hooks
`

describe('hook types', { timeout: 30000 }, () => {
    test('accepts a hooks file written against the published types', async (ctx) => {
        const result = await typeCheckHooksFile(ctx, validHooksFile)

        expect(result.stdout).toBe('')
        expect(result.exitCode).toBe(0)
    })

    test('accepts the hooks file generated by regit init', async (ctx) => {
        await ctx.regit('init 1.0.0')
        const generatedHooks = fs.readFileSync(
            path.join(ctx.tempDirLocal, '.regit', 'hooks.js'),
            'utf8'
        )

        const result = await typeCheckHooksFile(ctx, generatedHooks)

        expect(result.stdout).toBe('')
        expect(result.exitCode).toBe(0)
    })

    test('rejects a hook that returns the wrong type', async (ctx) => {
        const result = await typeCheckHooksFile(ctx, invalidHooksFile)

        const errors = result.stdout.split('\n').filter((line) => {
            return line.includes('error TS')
        })
        expect(errors).toHaveLength(1)
        expect(errors[0]).toMatch(/(^|\/)hooks\.js\(\d+,\d+\): error TS2322/)
    })
})
